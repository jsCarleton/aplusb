   Wasm_int.Int32.iadd of those arguments. Consolidated from what was
   originally six files (AddBytes/AddAst/AddCorrespondence/AddInvoke/
   AddSteps/AddCorrect) into this one; the section comments below mark
   those former boundaries. *)

