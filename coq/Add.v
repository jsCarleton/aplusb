(* =====================================================================
   Section: AST (formerly AddAst.v)

   Hand-encoded Coq AST for the add function defined in add.wat. This term
   is proved below (see "correspondence" section) to be byte-identical,
   via WasmCert-Coq's binary parser, to what wat2wasm actually compiles
   from add.wat -- so this term's correspondence with the .wat source is
   not merely asserted by eye, it is machine-checked. Local indices follow
   the .wat source: 0=$a (param) 1=$b (param).
   ===================================================================== *)

Definition l_a : localidx := 0%N.
Definition l_b : localidx := 1%N.

Definition add_body : list basic_instruction :=
  [:: BI_local_get l_a; BI_local_get l_b; BI_binop T_i32 (Binop_i BOI_add) ].

(* No non-parameter locals: modfunc_locals does not include the two
   parameters ($a, $b), which are supplied by function_type instead. *)
Definition add_locals : list value_type := [::].

Definition add_module_func : module_func :=
  {| modfunc_type := 0%N;
     modfunc_locals := add_locals;
     modfunc_body := add_body |}.

Definition add_function_type : function_type :=
  Tf [:: T_num T_i32; T_num T_i32] [:: T_num T_i32].

(* =====================================================================
   Section: correspondence (formerly AddCorrespondence.v)

   Trust chain: wat2wasm compiles add.wat -> add.wasm (trusted, external,
   outside Coq); tools/wasm_bytes_to_coq.py copies those exact bytes into
   add_wasm_bytes above (mechanical, no interpretation); WasmCert-Coq's
   binary parser (also outside the kernel's soundness argument, but its
   *output* here is checked *by* the kernel) turns those bytes into a
   `module` AST. This section proves, by kernel-checked computation, that
   the parsed function is identical to add_module_func -- the term every
   other section in this file is actually about. That closes the "did I
   transcribe the .wat correctly into Coq" gap: from here on,
   add_module_func is provably what wat2wasm actually produced from
   add.wat, not just a lookalike.
   ===================================================================== *)

Definition parsed_module : option module := run_parse_module add_wasm_bytes.

Lemma add_wasm_parses : exists m, parsed_module = Some m.
Proof. eexists. vm_compute. reflexivity. Qed.

Lemma add_wasm_func_matches :
